-- ============================================================================
-- 医学生人才信息库 · 068 更正 066 的因果归因（我推断错了）v1.0.0
--
-- 【我错在哪】
-- 066 里我写下这样的因果链：
--   "备份套件从 664 秒劣化到 7224 秒（2 小时）→ 根因是 change_log 占库 82%"
-- 并把它当成审计体量的问题写进了口径说明。
--
-- **实际原因是机器休眠**（用户指出）。一次 7224 秒的运行里有 1 小时 50 分的
-- 挂钟时间差异 —— 那正是会话中断的时长。
--
-- 【这是哪一类错误：从一次观察推断因果】
-- 我手上只有**一个** 7224 秒的观测值，就把它归因到我当时正在看的那个大数字上。
-- 这跟"两个变量一起变所以有因果"是同一个错误 —— 而且我刚刚在评审里
-- 反复强调"相关不是因果"、还在页面上写了固定警示。**我对自己也一样该用这个标准。**
-- 更该做的是：先看这个步骤**真的在干活还是被挂起**（例如去掉休眠变量重测一次），
-- 再谈归因。这次我重测了，见下面的事实。
--
-- 【更正后仍然成立的事实（这些是核过的）】
--   ① change_log 210.5 MB，占库 255 MB 的 **82%** —— 体量确实集中在这里；
--   ② 其中 **83.4%** 是机械重算类表（job_requirement/job_posting）产生的行 —— 核过；
--   ③ 那些行**没有信息量**：明细只有 `{"op":"UPDATE","row":"job_id=…","mode":"row"}`，
--      看不出改了哪一列 —— 抽查过；
--   ④ 050 之后 `job_requirement` 逐行审计已降到 34 行，但 **job_posting 仍有 31,790 行**
--      —— 按时间分组核过。
--
-- 所以 066 的改动**依然有价值**，但它的理由是"审计行没有信息量 + 体量集中"，
-- **不是**"它拖慢了备份"。本迁移把口径说明里的错误因果链删掉。
-- ============================================================================

BEGIN;
SET search_path TO mt, public;
SET client_min_messages = warning;

UPDATE metric_registry SET
  definition_note =
    'JD 解析类表（job_requirement / job_posting）产生的审计行 / 全部审计行。'
    '这些行绝大多数是"同一批岗位被重算"造成的，**信息量极低但体量很大** —— '
    '实测占 change_log 的 83.4%。'
    '⚠ **更正（迁移 068）**：066 曾在此写下"它把备份步骤从 664 秒拖到 7224 秒"，'
    '那是**错误归因** —— 那一次是机器休眠，不是性能劣化。'
    '本口径的价值在于"体量集中在哪里、这些行有没有信息量"，'
    '而不是"某个步骤慢是因为它"。',
  caveat =
    '本口径覆盖**历史累积**，所以它不会因为"触发逻辑修好了"而下降 —— '
    '下降要靠**归档历史噪声**，而那是保留策略的决策（rp_change_log 保留 60 个月，'
    '现有行全在保留期内）。本库只向前修，不擅自删。'
    '⚠ 归因纪律：看到某步骤变慢时，先确认它**真的在干活还是被挂起**'
    '（休眠、锁等待、网络超时都会表现成"慢"），再谈原因。'
 WHERE metric_id = 'M_AUDIT_NOISE_RATE';

UPDATE metric_registry SET
  definition_note =
    'change_log 占用的磁盘体量（MB）。**实测库 255 MB 里它占 210 MB（82%）** —— '
    '体量高度集中在这一张表上。'
    '⚠ **更正（迁移 068）**：066 曾写"它是回归里备份步骤耗时的主导项"，'
    '那是**未经核实的推断**；一次 7224 秒的运行实为机器休眠。'
    '完整备份天然随库体量增长，所以"备份慢"应当先测，不要先归因。',
  caveat =
    '体量大本身不是错（审计是合规资产），错的是**体量被零信息行占据**。'
    '看到它快速增长时，先用 M_AUDIT_NOISE_RATE 判断是"噪声"还是"真实变更"。'
 WHERE metric_id = 'M_AUDIT_CHANGELOG_MB';

DO $$
DECLARE n int;
BEGIN
  SELECT count(*) INTO n FROM metric_registry
   WHERE metric_id IN ('M_AUDIT_NOISE_RATE','M_AUDIT_CHANGELOG_MB')
     AND (definition_note LIKE '%更正（迁移 068）%');
  IF n <> 2 THEN RAISE EXCEPTION '两条口径的更正说明没写上（%）', n; END IF;
  RAISE NOTICE '已更正 066 的错误因果归因（实际是机器休眠）';
END $$;

COMMIT;
